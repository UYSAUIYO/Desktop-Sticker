/*  Desktop Sticker fork 专用：宿主嵌入层（外部 HWND 呈现）。               */
/*  不属于上游 Godot；由 .zcode/plans/ 的场景壁纸方案维护。                  */
/**************************************************************************/

#pragma once

#include <cstdint>
#include <windows.h>

#include "core/extension/libgodot.h"

// 非空 = 嵌入模式：引擎主窗口的呈现目标由宿主提供（桌面壁纸窗口）。
// 引擎不创建/不显示该窗口，也不改动它的样式、区域、IME 与属性。
HWND dstk_embed_present_hwnd();

// 给嵌入窗口装上"输入转发过程"（显示服务器建窗口时调用，宿主不需要直接调）。
//
// 为什么需要：嵌入模式用的是宿主的窗口，引擎原本**不子类化**它，所以宿主
// PostMessage 过来的 WM_MOUSEMOVE / WM_LBUTTONDOWN 只会落到宿主的窗口过程里，
// 引擎永远收不到。这里把窗口过程换成一个薄壳：鼠标消息原样交给
// DisplayServerWindows::WndProc（与真实窗口完全相同的处理——SetCapture、
// 按下计数、old_x/old_y、悬停进出都会正常维护），其余消息回交给宿主原来的过程。
//
// 这也是"桌面壁纸交互"的正确路径：宿主只负责把空白桌面上的鼠标消息转发进来，
// 之后按下期间由系统捕获把真实消息直接送到这个窗口，不再需要任何模拟注入。
void dstk_embed_install_input_proc();
