#pragma once

#include <cstdint>
#include <windows.h>

#include "core/extension/libgodot.h"

// 非空 = 嵌入模式：引擎主窗口的呈现目标由宿主提供（桌面壁纸窗口）。
// 引擎不创建/不显示该窗口，也不改动它的样式、区域、IME 与属性。
HWND dstk_embed_present_hwnd();

// 给嵌入窗口装上"输入转发过程"（显示服务器建窗口时调用，宿主不需要直接调）。
//
// 为什么需要：嵌入模式用的是宿主的窗口，引擎原本**不子类化**它，所以宿主的
// 窗口过程收到的输入消息不会进引擎。这里把窗口过程换成一个薄壳：
//   · 鼠标消息原样交给 DisplayServerWindows::WndProc —— 与真实窗口完全相同的
//     处理（SetCapture、按下计数、old_x/old_y、悬停进出都会正常维护）；
//   · 键盘消息（WM_KEYDOWN/UP、WM_SYSKEYDOWN/UP、WM_CHAR）同样交给它 —— 宿主的
//     低级键盘钩子在桌面是前台时把按键 PostMessage 进来；焦点移交（SetFocus）在
//     挂在 WorkerW 下的窗口上实测返回 87，只是"能拿就拿"的补充；
//   · 其余消息回交给宿主原来的过程。
//
// 这也是"桌面壁纸交互"的正确路径：宿主负责把空白桌面上的鼠标/键盘事件作为
// 真实窗口消息转发进来（不做模拟注入），引擎按原生输入路径处理。
void dstk_embed_install_input_proc();
