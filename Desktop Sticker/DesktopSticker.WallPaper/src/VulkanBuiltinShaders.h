// 内置着色器的 SPIR-V（④）。
//
// 为什么把 SPIR-V 直接嵌进来而不是运行时调 glslangValidator：用户自己的 GLSL 编译
// （子进程 + .spv 缓存）是独立的一步，那部分的逻辑（源码哈希 → 缓存键）可以单独测；
// 内置的这几对着色器是固定的，嵌进来最省事也最不容易出岔子。
//
// 重新生成（glslangValidator 由 tools/prepare_shaderc.ps1 构建）：
//   glslangValidator -V --target-env vulkan1.1 -o X.spv <源文件>
//
// ---- fullscreen.vert（全屏三角形，不用顶点缓冲）----
// #version 450
// void main() {
//     vec2 p = vec2((gl_VertexIndex << 1) & 2, gl_VertexIndex & 2);
//     gl_Position = vec4(p * 2.0 - 1.0, 0.0, 1.0);
// }

// ---- default.frag（默认全屏等离子）----
// #version 450
// layout(location = 0) out vec4 outColor;
// layout(push_constant) uniform Push {
//     vec4 iTime;        // x = 秒
//     vec4 iResolution;  // xy = 像素尺寸
// } pc;
// void main() {
//     vec2 uv = gl_FragCoord.xy / pc.iResolution.xy;
//     float t = pc.iTime.x;
//     float v = sin(uv.x * 8.0 + t) + sin(uv.y * 10.0 - t * 1.3)
//             + sin((uv.x + uv.y) * 6.0 + t * 0.7);
//     vec3 c = 0.5 + 0.5 * cos(vec3(0.0, 2.1, 4.2) + v + t);
//     outColor = vec4(c, 1.0);
// }

// ---- mesh.vert（32 面体：MVP + 法线/颜色传递）----
// #version 450
// // 内置 3D 模型（32 面体）的顶点着色器
// layout(location = 0) in vec3 inPosition;
// layout(location = 1) in vec3 inNormal;
// layout(location = 2) in vec3 inColor;
// 
// layout(location = 0) out vec3 vColor;
// layout(location = 1) out vec3 vNormal;
// layout(location = 2) out vec3 vWorldPos;
// 
// layout(set = 0, binding = 0) uniform Scene {
//     mat4 viewProj;
//     mat4 model;
//     vec4 lightDir;   // xyz = 指向光源的方向（世界空间，已归一化）
//     vec4 eyePos;     // xyz = 相机位置
//     vec4 misc;       // x = 秒
// } u;
// 
// void main() {
//     vec4 world = u.model * vec4(inPosition, 1.0);
//     vWorldPos = world.xyz;
//     // 本场景的模型矩阵只有旋转与均匀缩放，直接取 mat3 变换法线即可
//     vNormal = normalize(mat3(u.model) * inNormal);
//     vColor = inColor;
//     gl_Position = u.viewProj * world;
// }

// ---- mesh.frag（单向光 + Blinn-Phong）----
// #version 450
// // 内置 3D 模型（32 面体）的片元着色器：单向光 + Blinn-Phong
// layout(location = 0) in vec3 vColor;
// layout(location = 1) in vec3 vNormal;
// layout(location = 2) in vec3 vWorldPos;
// 
// layout(location = 0) out vec4 outColor;
// 
// layout(set = 0, binding = 0) uniform Scene {
//     mat4 viewProj;
//     mat4 model;
//     vec4 lightDir;
//     vec4 eyePos;
//     vec4 misc;
// } u;
// 
// void main() {
//     vec3 N = normalize(vNormal);
//     vec3 L = normalize(u.lightDir.xyz);
//     vec3 V = normalize(u.eyePos.xyz - vWorldPos);
//     vec3 H = normalize(L + V);
// 
//     float ambient  = 0.18;
//     float diffuse  = max(dot(N, L), 0.0);
//     float specular = pow(max(dot(N, H), 0.0), 48.0) * 0.35;
// 
//     vec3 color = vColor * (ambient + diffuse) + vec3(specular);
//     outColor = vec4(pow(color, vec3(1.0 / 1.1)), 1.0);
// }

